"""Create (or reset) the two confirmed dev test users and write .env.test.

Usage, from the repo root with the virtual env active:

    python scripts/dev/create_test_users.py

Reads SUPABASE_URL and SUPABASE_SERVICE_KEY from the root .env. Refuses to run
unless ENV=development. Each run sets a fresh random password for both users,
so it is safe to re-run. Credentials go to .env.test (git-ignored) and are
never printed.
"""

from __future__ import annotations

import os
import secrets
import string
import sys
from pathlib import Path

from dotenv import load_dotenv

from supabase import create_client

ROOT = Path(__file__).resolve().parents[2]
ENV_FILE = ROOT / ".env"
OUT_FILE = ROOT / ".env.test"

TEST_USERS = {
    "A": "reader.a@test.local",
    "B": "reader.b@test.local",
}


def strong_password(length: int = 32) -> str:
    """Random password with at least one lower, upper, digit and symbol."""
    symbols = "-_.~"
    alphabet = string.ascii_letters + string.digits + symbols
    while True:
        pw = "".join(secrets.choice(alphabet) for _ in range(length))
        if (
            any(c.islower() for c in pw)
            and any(c.isupper() for c in pw)
            and any(c.isdigit() for c in pw)
            and any(c in symbols for c in pw)
        ):
            return pw


def find_user_id(admin, email: str) -> str | None:
    page = 1
    while True:
        users = admin.list_users(page=page, per_page=200)
        if not users:
            return None
        for user in users:
            if (user.email or "").lower() == email:
                return user.id
        page += 1


def main() -> int:
    load_dotenv(ENV_FILE)

    env = os.getenv("ENV", "")
    if env != "development":
        print(f"Refusing to run: ENV is {env!r}, expected 'development'.")
        return 1

    url = os.getenv("SUPABASE_URL")
    service_key = os.getenv("SUPABASE_SERVICE_KEY")
    if not url or not service_key:
        print("SUPABASE_URL and SUPABASE_SERVICE_KEY must be set in .env.")
        return 1

    admin = create_client(url, service_key).auth.admin

    lines = [
        "# Dev test users. Generated by scripts/dev/create_test_users.py.",
        "# Git-ignored. Do not commit. Re-run the script to rotate passwords.",
    ]
    for label, email in TEST_USERS.items():
        password = strong_password()
        user_id = find_user_id(admin, email)
        if user_id is None:
            created = admin.create_user(
                {"email": email, "password": password, "email_confirm": True}
            )
            user_id = created.user.id
            action = "created"
        else:
            admin.update_user_by_id(
                user_id, {"password": password, "email_confirm": True}
            )
            action = "password reset"

        user = admin.get_user_by_id(user_id).user
        confirmed = user.email_confirmed_at is not None
        print(f"{email}: {action}, id={user_id}, confirmed={confirmed}")
        if not confirmed:
            print(f"{email} is not confirmed; aborting without writing {OUT_FILE.name}.")
            return 1

        lines += [
            "",
            f"TEST_USER_{label}_EMAIL={email}",
            f"TEST_USER_{label}_PASSWORD={password}",
            f"TEST_USER_{label}_ID={user_id}",
        ]

    OUT_FILE.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"Wrote {OUT_FILE.relative_to(ROOT)} (passwords not shown).")
    return 0


if __name__ == "__main__":
    sys.exit(main())
