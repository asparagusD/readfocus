"""Write docs/repo-graph/AGENT_GRAPH.md from the compiled LangGraph workflow.

The diagram is `workflow.get_graph().draw_mermaid()` as LangGraph draws it,
plus a table of the events and the node each one enters. Not part of
`make graph`, which uses the standard library only and runs in CI without
Supabase settings; run it with the virtualenv active and `.env` in place:

    python scripts/export_agent_graph.py

backend/tests/test_graph_doc.py fails when the committed file is stale.
"""

from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "docs" / "repo-graph" / "AGENT_GRAPH.md"


def render() -> str:
    from backend.agents import graph

    rows = "\n".join(f"| `{event}` | `{node}` |" for event, node in graph.ENTRY.items())
    mermaid = graph.workflow.get_graph().draw_mermaid().strip()
    return f"""# Agent graph

Generated by `scripts/export_agent_graph.py` from the compiled workflow in
`backend/agents/graph.py` (`workflow.get_graph().draw_mermaid()`). Do not
edit by hand; regenerate it instead. Dotted arrows are conditional edges.

| Event | First node |
|---|---|
{rows}

Any other event goes straight to `__end__`. Runs go through
`backend/agents/workflow.py`, which sets the recursion limit, and each run's
decisions are stored in `agent_decisions` (migration 009).

```mermaid
{mermaid}
```
"""


def main() -> None:
    OUT.write_text(render(), encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(ROOT).as_posix()}")


if __name__ == "__main__":
    import sys

    sys.path.insert(0, str(ROOT))
    main()
